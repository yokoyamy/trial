## 72. API URL

JavaScriptから本アプリAPIを呼び出す場合は、現在表示されているindex.phpを基準にURLを生成する。

実行環境固有のURLを固定記述してはならない。

API URLの生成によって、

- ホスト
- ポート
- HTTP / HTTPS
- 配置場所

が変更されても自身のAPIを呼び出せることを必須とする。


## 73. APIレスポンス

APIはJSONを返す。

成功例：

    {
      "success": true,
      "message": "処理が完了しました。"
    }

失敗例：

    {
      "success": false,
      "message": "入力内容を確認してください。",
      "errors": {}
    }

JSON以外のHTMLをAPIレスポンスへ混在させない。

JSON出力後は処理を終了する。

---

## 74. HTTPステータス

基本的に以下を使用する。

- 200 正常終了
- 400 入力不正
- 401 認証失敗
- 403 CSRF・権限等による拒否
- 404 対象データなし
- 409 データ競合・二重実行
- 500 サーバー内部エラー
- 502 外部サービス通信エラー

---

## 75. fetchエラー

通信失敗時に単に、

    サーバーとの通信に失敗しました。

だけを表示して終了しない。

可能な範囲で以下を判定する。

- HTTPステータス
- JSONレスポンスの有無
- API message
- validation error
- CSRFエラー
- 認証エラー
- 権限エラー
- 競合エラー
- サーバーエラー
- 外部サービス通信エラー

JSONが返らない場合は、その事実を利用者へ分かる形で表示する。

---

## 76. 入力保持

通信失敗時に入力内容を消去しない。

保存失敗時にも入力内容を保持する。

ただし、パスワードはlocalStorage等へ保存しない。

---

## 77. JavaScript

すべてのJavaScript処理は、

    document.addEventListener('DOMContentLoaded', ...)

の内部で実行する。

イベント登録前に対象要素の存在を確認する。

対象要素が存在しない場合は、その処理だけを行わず、他の処理を継続する。

---

## 78. 非同期通信中のUI

非同期通信を開始する前に、

1. 対象ボタンをdisabled=trueにする
2. ローディング表示を付ける
3. fetchを開始する

の順番を必須とする。

通信完了後はfinallyで、

1. disabled=false
2. ローディング表示を解除する

を行う。

---

## 79. XSS対策

PHPからHTMLへ動的な値を出力する場合は共通エスケープ処理を使用する。

安全な文字列エスケープ関数をアプリ固有の名前空間内に定義する。

JavaScriptからDOMへ値を表示する場合は原則としてtextContentを使用する。

innerHTMLを使用する場合は、使用する値が安全であることを明確に確認する。

回答内容など利用者が入力した文字列をHTMLとして解釈してはならない。

---

## 80. PHP名前空間

PHPファイル先頭にはアプリ固有の階層型名前空間を使用する。

本アプリでは、

    namespace yokoyamy\trial\newapp;

を使用する。

汎用的な単一単語の名前空間は使用しない。


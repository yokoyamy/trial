# アンケート業務運営アプリ 実装要件
## 全差し替え版

---

## 1. 基本方針

本アプリは、アンケート運営に必要な以下の業務を一つのWebアプリで管理する。

- アンケートの作成
- アンケートの編集
- アンケートの削除
- アンケートの公開
- アンケートの終了
- 顧客一覧の取得
- 送信対象者の選択
- アンケートメールの送信
- 送信結果の確認
- 回答受付
- 回答状況の確認
- 回答結果の集計
- メール送信設定
- kintone接続設定

本番版では、モック上だけで完結している処理を正式なサーバー処理へ置き換える。

画面上の値を変更しただけでは、保存・公開・終了・送信・回答完了などの処理が成立したものとは扱わない。

すべての状態変更はサーバー側で最終判断する。

---

## 2. 動作環境

以下を動作環境とする。

- Apache 2.4
- PHP 8.4 / 8.5
- Windows / Unix
- データベースなし
- HTML / CSS / JavaScript / PHPを1つのindex.phpへ格納
- UTF-8
- 永続データはアプリルート配下のJSONファイルへ保存
- PHPによる外部HTTP通信ではcURLを使用しない

本アプリはApacheからHTTPまたはHTTPSによってWebページとして提供される。

---

## 3. index.phpの実行方法

index.phpは通常のWebページとしてHTTPまたはHTTPSで提供する。

以下を動作対象外とする。

- file://による直接表示
- data: URLからの表示
- sandbox属性によって同一オリジンが無効化されたiframe内での表示
- Originがnullとなるその他の実行環境

index.phpをブラウザから直接開いた場合、現在表示しているindex.php自身をアプリ内APIの基準とする。

実行環境の違いによって変化する以下の情報をコードへ固定してはならない。

- ホスト名
- IPアドレス
- ポート番号
- HTTP / HTTPS
- アプリ配置ディレクトリ
- 本番環境固有のURL

特定の実行環境を示すURLをサンプルとして記載する必要がある場合でも、実装コードへ埋め込んではならない。

---

## 4. アプリ自身へのAPI通信

JavaScriptからアプリ自身のAPIを呼び出す場合は、現在表示されているindex.phpを基準としてAPI URLを生成する。

API通信先として、実行環境固有の絶対URLを使用してはならない。

例えば以下のような固定指定は禁止する。

- 特定のホスト名を含むURL
- 特定のIPアドレスを含むURL
- 特定のポート番号を含むURL
- 開発環境専用URL
- 本番環境専用URL

実行環境が変更されても、同じindex.phpをそのまま使用できることを必須とする。

---

## 5. 同一オリジン通信

アプリ内部APIへの通信は、現在表示しているindex.phpと同じオリジンで行う。

状態変更を伴う通信では、

- セッションCookie
- CSRFトークン

を利用する。

本アプリ自身のAPI利用を目的とした外部CORS設定は行わない。

以下は禁止する。

    Access-Control-Allow-Origin: *

    Access-Control-Allow-Origin: null

また、任意の外部Originからセッション付きAPIを利用可能にする設定は禁止する。

---

## 6. Originがnullの場合

ブラウザからのリクエストでOriginがnullとなった場合は、通常の本番利用環境ではないものとして扱う。

以下を確認する。

- file://で開いていないか
- sandbox iframeではないか
- data: URLではないか
- その他のopaque originではないか

Origin:nullを許可するためにCORS設定を緩和してはならない。

---

## 7. API URLに関する禁止事項

JavaScriptへ以下を固定記述してはならない。

- 実行環境固有のホスト名
- 実行環境固有のIPアドレス
- 実行環境固有のポート
- 実行環境固有のスキーム
- 実行環境固有のディレクトリを含む絶対URL

API URLは現在表示されているindex.phpを基準として生成する。

これにより、開発環境、本番環境、移設後の環境で同じコードを使用できることを必須とする。

---

## 8. 管理者画面と回答者画面

本アプリには、

- アンケート運営者向け画面
- アンケート回答者向け画面

の2種類が存在する。

回答者画面には運営者向け機能を表示しない。

回答者画面には以下を表示しない。

- 運営者向けメニュー
- 設定画面へのリンク
- アンケート管理画面への戻る操作
- 顧客一覧
- メール設定
- kintone設定
- アンケート管理操作

回答者画面から運営者画面へ移動する導線を設けない。

---

## 9. 運営者の認証

運営者向け機能については、運営者以外が以下を実行できない構成とする。

- 設定変更
- アンケート変更
- アンケート削除
- アンケート公開
- アンケート終了
- 顧客更新
- メール送信
- その他の管理操作

独自のログイン画面を追加するかどうかは、別途決定した認証方式に従う。

認証方式が決定していない場合は、本番実装開始前に確定する。

認証方式を実装者が独自判断して変更してはならない。

---

## 10. データ保存方式

データベースは使用しない。

アプリルート配下のJSONファイルを正式なデータ保存先とする。

基本構成：

    data/
    ├─ settings.json
    ├─ customers.json
    ├─ surveys.json
    ├─ responses.json
    └─ mail_logs.json

必要に応じて一時ファイルを使用できる。

JSONファイルはUTF-8で保存する。

---

## 11. JSONファイルへの直接アクセス禁止

data配下のJSONファイルをブラウザから直接取得できない状態とする。

特にsettings.jsonには認証情報が含まれるため、外部から直接取得できてはならない。

以下のような直接取得を禁止する。

    /data/settings.json
    /data/customers.json
    /data/surveys.json
    /data/responses.json
    /data/mail_logs.json

---

## 12. JSON保存の共通ルール

JSON保存では以下を必須とする。

- 排他制御
- 正しいJSON形式
- UTF-8保存
- 保存途中で既存データを破壊しない
- 保存失敗時に既存データを維持する
- 保存後に再読み込みして確認する
- 同時更新によるJSON破損を防止する

保存は一時ファイルへの書き込みなど、途中状態が正式ファイルとして扱われない方法を使用する。

---

## 13. JSON破損時

JSON読み込み時に以下を検出した場合はデータ破損として扱う。

- JSONとして解析できない
- 必須項目がない
- 型が不正
- 配列であるべき値が配列ではない
- オブジェクトであるべき値がオブジェクトではない
- 状態値が許可された値ではない

破損したJSONを正常なデータとして上書きしてはならない。

利用者には安全なエラーメッセージを表示する。

例：

    データを読み込めませんでした。
    管理者へ確認してください。

JSONの内部内容、パスワード、認証情報などを画面へ表示してはならない。

---

## 14. データ更新競合

複数の画面または複数の利用者が同じデータを更新した場合、古い画面による無条件の上書きを防止する。

以下について競合を検出する。

- アンケート編集
- アンケート公開
- アンケート終了
- メール設定
- kintone設定
- 顧客一覧更新

更新時には、読み込み時点のデータ版または更新日時を利用して競合を検出する。

古いデータからの更新である場合は保存しない。

競合時はHTTP 409を返す。

利用者には、

    他の画面でデータが更新されています。
    画面を再読み込みしてからもう一度お試しください。

などのメッセージを表示する。

---

## 15. settings.json

settings.jsonには以下を保存する。

    {
      "version": 1,
      "mail": {
        "smtp_server": "",
        "smtp_port": 587,
        "security": "STARTTLS",
        "authentication": false,
        "username": "",
        "password": "",
        "from_address": "",
        "from_name": "",
        "configured": false,
        "verified": false,
        "updated_at": ""
      },
      "kintone": {
        "domain": "",
        "app_id": "",
        "login_name": "",
        "password": "",
        "proxy_host_port": "",
        "proxy_enabled": false,
        "ssl_verify": false,
        "customer_id_field": "",
        "customer_name_field": "",
        "customer_email_field": "",
        "configured": false,
        "verified": false,
        "updated_at": ""
      }
    }

画面表示用データにはパスワードを含めない。

APIレスポンスにもパスワードを含めない。

---

## 16. パスワード保持

設定変更時にパスワード欄が空欄の場合は既存パスワードを保持する。

空欄を理由として既存パスワードを削除してはならない。

パスワードを変更する場合だけ新しい値へ変更する。

画面再表示時には実際のパスワードを表示しない。

JavaScriptのlocalStorageへパスワードを保存してはならない。

---

## 17. メール設定

設定できる項目：

- SMTPサーバ
- ポート番号
- 接続方式
- SMTP認証の使用有無
- 認証ユーザー名
- 認証パスワード
- 送信元メールアドレス
- 送信元名

接続方式は以下だけを許可する。

- なし
- STARTTLS
- SSL/TLS

必須項目：

- SMTPサーバ
- ポート番号
- 送信元メールアドレス

SMTP認証を使用する場合：

- 認証ユーザー名
- 認証パスワード

を必須とする。

---

## 18. メール設定バリデーション

サーバー側で以下を検証する。

- SMTPサーバが入力されている
- SMTPサーバに改行がない
- ポート番号が数値である
- ポート番号が1～65535の範囲である
- 接続方式が許可された値である
- 送信元メールアドレスが正しい形式である
- 送信元名に改行がない
- ユーザー名に不正な改行がない
- 各項目の最大文字数を超えていない

メールヘッダーインジェクションにつながる入力を許可しない。

画面側のバリデーションだけを信用してはならない。

---

## 19. メール設定状態

メール設定は以下を区別する。

- 未設定
- 設定済み
- 接続確認済み
- 接続エラー

設定保存だけでは接続確認済みとしない。

設定内容が変更された場合は、

    verified = false

とする。

実際のSMTP接続確認が成功した場合だけ、

    verified = true

とする。

---

## 20. SMTP接続確認

「送信設定を確認」は実際のSMTP接続確認を行う。

入力値だけの検査を接続確認成功として扱わない。

以下を確認する。

- SMTPサーバへ接続できる
- 指定ポートへ接続できる
- 指定した接続方式を利用できる
- SMTP認証を使用する場合は認証できる
- タイムアウトを適切に処理する

失敗時にはパスワードその他の認証情報を表示しない。

---

## 21. SMTPメール送信方式

メール送信は保存されたSMTP設定を使用する。

送信処理では、

- 送信元
- 宛先
- 件名
- 本文
- 回答者用URL

を正しく設定する。

メールアドレスおよびメールヘッダーに改行を含む値を使用してはならない。

送信処理の失敗は対象者ごとに記録する。

---

## 22. kintone設定

設定できる項目：

- kintone利用先
- 顧客管理アプリID
- ログイン名
- パスワード
- プロキシ

APIトークンは使用しない。

認証にはkintoneログイン名とパスワードを使用する。

---

## 23. kintone利用先

入力として以下を受け付ける。

    example

    example.cybozu.com

    https://example.cybozu.com

入力値を正規化し、1つの正規化済みURLとして扱う。

https://や.cybozu.comを二重付与してはならない。

URL生成処理はアプリ内で統一する。

---

## 24. kintoneプロキシ

プロキシは任意設定とする。

入力形式：

    host:port

プロキシが設定されている場合、kintoneへのすべての通信で同じプロキシ設定を使用する。

プロキシ通信では、

- proxy
- request_fulluri = true

を適用する。

プロキシが空の場合は通常通信とする。

プロキシ認証は使用しない。

プロキシのユーザー名・パスワード入力欄は設けない。

---

## 25. kintone通信

kintoneへの通信ではcURLを使用しない。

以下を使用する。

- stream_context_create
- file_get_contents

SSL証明書検証は無効固定とする。

画面からSSL検証を変更する項目は設けない。

---

## 26. kintone認証

認証ヘッダーには、

    X-Cybozu-Authorization

を使用する。

Base64化する文字列は、

    trim(ログイン名) . ":" . trim(パスワード)

とする。

以下をログ・画面・APIレスポンスへ出力してはならない。

- パスワード
- Authorizationヘッダー
- Base64化された認証情報
- セッション情報

---

## 27. kintone接続確認

「接続設定を確認」では実際にkintone APIへアクセスする。

顧客管理アプリIDが設定されている場合は、そのアプリを対象として確認する。

使用するAPIは、

    /k/v1/app.json?id={app_id}

または、

    /k/v1/apps.json?limit=1

とする。

入力値だけを検査して接続確認成功としてはならない。

---

## 28. kintone API GET

GETではリクエスト本文を送信しない。

パラメータはURLへ付与する。

クエリ文字列は、

    http_build_query($params, '', '&', PHP_QUERY_RFC3986)

で生成する。

GET通信でcontentを設定してはならない。

---

## 29. kintone API POST / PUT

POST / PUTではJSON形式で送信する。

JSONは、

    json_encode($data, JSON_UNESCAPED_UNICODE)

で生成する。

Content-Typeは、

    application/json

とする。

---

## 30. kintoneエラー

kintoneからエラーが返った場合は可能な範囲で、

- HTTPステータス
- code
- message
- errors

を取得する。

利用者には原因を判断できる安全な範囲だけを表示する。

以下は表示しない。

- パスワード
- Authorization
- Base64認証情報
- セッション情報
- プロキシ認証情報

---

## 31. 顧客情報

顧客情報はkintoneの顧客管理アプリから取得する。

最低限以下を取得する。

- 顧客ID
- 顧客名
- メールアドレス

kintoneのどの項目を使用するかを設定できるようにする。

最低限、

- 顧客ID項目
- 顧客名項目
- メールアドレス項目

を設定できる。

項目対応が未設定の場合は顧客取得成功として扱わない。

---

## 32. 顧客情報のバリデーション

kintoneから取得した顧客情報についてサーバー側で以下を確認する。

- 顧客IDが存在する
- 顧客名が文字列である
- メールアドレスが文字列である
- メールアドレスが妥当な形式である
- 必要な項目が欠落していない

不正な顧客データは送信対象として使用しない。

---

## 33. 顧客一覧の全件取得

kintoneの取得上限をもって全顧客取得完了と判断してはならない。

複数回取得が必要な場合は、すべての対象データを取得する。

取得途中で失敗した場合はcustomers.jsonを新しいデータで更新しない。

---

## 34. customers.json

顧客一覧を保存する場合は以下を記録する。

    {
      "version": 1,
      "updated_at": "",
      "source": "kintone",
      "count": 0,
      "customers": []
    }

customersには最低限、

- customer_id
- name
- email

を保存する。

パスワード、認証情報、CSRFトークンなどは保存しない。

顧客一覧更新失敗時は既存の正常な顧客一覧を破壊しない。

---

## 35. アンケートデータ

アンケートには最低限以下を保持する。

- アンケートID
- アンケート名
- 説明
- 状態
- 作成日時
- 更新日時
- 公開開始日時
- 公開終了日時
- 質問番号形式
- グループ
- 質問
- 選択肢
- 必須／任意
- 分岐設定
- データ版

状態は以下だけを使用する。

    draft
    open
    closed

---

## 36. アンケートID

アンケートIDは一意とする。

質問ID、選択肢ID、グループIDもそれぞれ一意とする。

表示用の質問番号と質問IDを分離する。

質問の並べ替え・削除によって表示番号が変わっても質問IDは変更しない。

---

## 37. アンケート作成・編集

以下を同一画面で編集できる。

- 基本情報
- グループ
- 質問
- 選択肢
- 必須／任意
- 分岐
- 並び順

質問ごとに別画面へ移動しない。

モックと同じ業務上の流れを維持する。

---

## 38. 回答形式

回答形式は以下だけを許可する。

- free
- single
- multiple

自由記述には選択肢を保存しない。

single / multipleには1個以上の選択肢を必要とする。

---

## 39. 質問バリデーション

保存時および公開時にサーバー側で以下を確認する。

- 質問IDが一意
- 質問文が空でない
- 質問文が上限文字数以内
- 回答形式が許可された値
- 必須設定がbooleanとして正しい
- single / multipleの場合は選択肢が1個以上
- 選択肢IDが一意
- 選択肢文が空でない
- 選択肢文が上限文字数以内
- freeには選択肢がない
- 不正な項目が存在しない

---

## 40. 分岐

分岐はsingle質問だけで利用できる。

選択肢ごとに、

- 分岐なし
- 次の質問
- 指定した質問
- アンケート終了

を指定できる。

存在しない質問IDを分岐先として保存しない。

削除・並べ替え後も分岐先の整合性を確認する。

公開前に分岐を検証する。

---

## 41. 分岐の循環

分岐によって質問を循環する構造を作ってはならない。

公開前にサーバー側で循環を検出する。

循環が存在する場合は公開しない。

---

## 42. 公開期間

公開開始日時・公開終了日時を保存する。

公開期間が設定されている場合は、その期間外では回答できない。

open状態でも、

- 公開開始前
- 公開終了後

は回答受付を行わない。

終了操作を行った場合は、公開終了日時に関係なく回答受付を終了する。

---

## 43. 公開処理

公開前にサーバー側で再検証する。

最低限以下を確認する。

- アンケート名
- グループ
- 質問
- 質問文
- 回答形式
- 選択肢
- 必須設定
- 分岐
- 公開期間

不備がある場合は公開しない。

公開操作はPOSTで実行する。

---

## 44. 公開後の編集

公開中アンケートについて、回答データとの整合性を壊す変更を無条件に許可しない。

回答済みデータが存在するアンケートでは、以下を原則として禁止する。

- 回答済み質問の削除
- 回答済み選択肢の削除
- 回答形式の変更
- 回答済み質問のID変更
- 回答済み選択肢のID変更
- 分岐構造を壊す変更

公開後に変更可能な項目と変更不可の項目をサーバー側で判定する。

必要な変更は新しいアンケートとして作成する方式を基本とする。

---

## 45. アンケート削除

原則としてdraft状態だけを削除対象とする。

回答データまたは送信履歴が存在するアンケートを物理削除しない。

削除操作ではサーバー側で状態を再確認する。

---

## 46. surveys.json

基本構造：

    {
      "version": 1,
      "updated_at": "",
      "surveys": []
    }

各アンケートには、

- id
- name
- description
- status
- created_at
- updated_at
- publish_start_at
- publish_end_at
- numbering
- version
- groups

を保存する。

---

## 47. 回答者用URL

公開されたアンケートには回答者用URLを発行する。

アンケートIDだけをURLへ含め、それだけで回答できる構成にしてはならない。

回答者用URLには推測困難な識別情報を使用する。

回答者用識別情報は十分な長さのランダム値とする。

回答者用識別情報は重複してはならない。

回答者用URLから以下のアンケートへ回答できない。

- draft
- closed
- 公開期間外

---

## 48. 回答者識別

メール送信対象者については、

- アンケートID
- 顧客ID
- 回答者用識別情報
- 送信履歴

を関連付ける。

顧客一覧に存在しない回答者からの回答も許可する。

顧客一覧に存在しないことを理由として回答を拒否しない。

---

## 49. 回答データ

responses.jsonには最低限以下を保存する。

- 回答ID
- アンケートID
- 回答者識別情報
- 顧客ID
- 回答日時
- 回答完了状態
- アンケート定義の版
- 質問ID
- 回答内容

回答時点の質問・選択肢を識別できる情報を保持する。

現在のアンケート定義だけに依存して過去回答を解釈してはならない。

---

## 50. 回答サーバー側検証

回答者画面のチェックだけを信用しない。

回答保存時にサーバー側で以下を検証する。

- アンケートが存在する
- open状態である
- 公開期間内である
- 回答者用識別情報が有効
- 質問IDが存在する
- 不正な質問IDが含まれていない
- 必須質問が回答されている
- 回答形式が一致している
- singleが1件だけである
- multipleが許可された選択肢だけである
- 選択肢IDが存在する
- freeの文字数が上限以内
- 不正な回答項目が含まれていない

---

## 51. 回答の二重送信

同じ回答を二重登録しない。

回答送信時には一意な送信識別情報を使用する。

同一の送信識別情報が再送された場合は、既存回答を重複登録しない。

ネットワーク障害による再送でも二重登録されないようにする。

---

## 52. 回答完了

回答保存成功後だけ回答完了とする。

保存成功前に完了画面を表示してはならない。

保存成功後は同じ回答者用識別情報による再送信を受け付けない。

---

## 53. responses.json

基本構造：

    {
      "version": 1,
      "updated_at": "",
      "responses": []
    }

回答データはアンケート単位で検索可能な構造とする。

回答者識別情報と送信履歴を関連付けられる構造とする。

---

## 54. 回答率

回答率は、

    回答完了者数 ÷ 実際のメール送信対象者数 × 100

を基本とする。

メール送信対象外の顧客を母数へ含めない。

顧客一覧に存在しない回答者からの自発的な回答は回答数に含める。

ただしメール送信対象者数は増加させない。

送信対象者数が0の場合、回答率を0%として扱うか「算出対象なし」と表示するかを統一する。

---

## 55. 回答結果集計

回答結果はresponses.jsonを正式なデータとして集計する。

顧客一覧に登録されていない回答者も集計対象とする。

質問ごとに、

- 回答数
- 未回答数
- 割合

を表示できるようにする。

---

## 56. 単一選択集計

single質問では選択肢ごとに、

- 回答数
- 割合

を表示する。

割合の母数は、その質問への有効回答数とする。

---

## 57. 複数選択集計

multiple質問では選択肢ごとの選択回数を集計する。

一人が複数選択した場合は、それぞれを1回として集計する。

割合は、

    選択肢の選択回数
    ÷
    複数選択質問への回答者数
    × 100

とする。

---

## 58. 自由記述集計

free質問では回答内容を一覧表示する。

回答内容はHTMLとして解釈しない。

HTML、JavaScript、その他の文字列が含まれていても実行されない。

---

## 59. メール送信

メール送信前にサーバー側で以下を確認する。

- アンケートが存在する
- アンケートがopen状態
- 公開期間内
- メール設定が存在する
- SMTP設定が有効
- SMTP接続確認済み
- 送信対象者が1名以上
- 送信先メールアドレスが妥当
- 件名が入力されている
- 本文が入力されている
- 回答者用URLを生成できる
- 対象者が有効である

いずれかに問題がある場合は送信処理を開始しない。

---

## 60. 送信対象者

送信対象者は顧客一覧から選択する。

以下を行える。

- 顧客検索
- 複数選択
- 選択解除
- 選択者確認

送信実行前に、

- 対象者数
- 対象者一覧

を確認できる。

---

## 61. メール内容

送信前に、

- 件名
- 本文
- 回答用案内

を確認・編集できる。

回答用案内には回答者用URLを含める。

回答者用URLは対象者ごとに正しく生成する。

---

## 62. メール送信確認

送信前に確認画面を表示する。

確認画面では、

- アンケート名
- 送信対象者数
- 送信対象者
- 件名
- 本文
- 回答用案内

を確認できる。

確認後に送信を実行する。

---

## 63. メール送信の二重実行

送信処理中は送信ボタンを無効化する。

サーバー側でも同一送信処理の重複実行を防止する。

同一の送信処理識別情報による再実行では、同じ対象者へ二重送信しない。

---

## 64. メール送信履歴

mail_logs.jsonへ送信結果を保存する。

最低限以下を保存する。

- 送信履歴ID
- 送信処理識別情報
- アンケートID
- 送信日時
- 送信対象者数
- 成功数
- 失敗数
- 対象者ごとの結果
- 失敗理由

パスワード、認証情報、CSRFトークンなどは保存しない。

---

## 65. 部分送信失敗

一部の対象者への送信に失敗した場合でも、成功した対象者を失敗扱いにしない。

対象者ごとに、

- 成功
- 失敗

を記録する。

失敗理由は利用者が再送判断できる範囲だけを表示する。

---

## 66. 再送

送信失敗者を確認できるようにする。

再送する場合は、過去の送信履歴を上書きしない。

再送は新しい送信履歴として記録する。

成功済みの対象者を誤って再送しないよう、再送対象者を明示的に選択する。

---

## 67. mail_logs.json

基本構造：

    {
      "version": 1,
      "updated_at": "",
      "logs": []
    }

各送信履歴には対象者ごとの送信結果を保持する。

送信済み・失敗・再送の関係を追跡できる構造とする。

---

## 68. CSRF

状態変更を伴うすべての操作でCSRF検証を行う。

対象には少なくとも以下を含む。

- メール設定保存
- SMTP接続確認
- kintone設定保存
- kintone接続確認
- 顧客一覧更新
- アンケート保存
- アンケート削除
- アンケート公開
- アンケート終了
- メール送信
- 回答保存

CSRF検証失敗時は処理を実行せずHTTP 403を返す。

---

## 69. セッション

セッションはアプリ固有の領域を使用する。

ルート直下の汎用セッションキーを使用しない。

セッションCookieには、

- HttpOnly
- SameSite=Lax

を適用する。

---

## 70. CSRFトークン

CSRFトークンは新規セッション時に生成する。

十分な長さの暗号学的に安全なランダム値を使用する。

同一セッションで画面を再表示しただけではCSRFトークンを変更しない。

セッションID再生成時には必要に応じてCSRFトークンも再発行する。

CSRFトークンをログ、画面、JSONファイルへ保存してはならない。


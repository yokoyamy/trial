# 【詳細要約】アンケート管理システム 要件定義書

---

## 1. プロジェクト概要・設計方針

* **1.1 目的:**  
  Web上でのアンケート作成・公開・顧客へのメール個別送信・回答集計/分析、およびkintone（cybozu.com）との顧客データ連携を一元管理し、運用業務を効率化・省力化する。
* **1.2 対象ユーザー:**  
  * アンケート運営担当者（管理者）  
  * アンケート回答者（顧客・一般ユーザー）
* **1.3 全体設計方針:**  
  * **一覧画面を中心とした動線:** すべての操作の起点を「アンケート一覧画面」とし、迷いのない画面遷移を実現。  
  * **レスポンシブ対応:** 管理画面はPC利用を主としつつ、外出先からのスマートフォン・タブレット操作を考慮し、テーブルの横スクロール対応やタップしやすいボタンサイズを確保。  
  * **固定共通ヘッダー:** `[アンケート一覧]`、`[キントーン連携設定]`、`[ログアウト]` を常時固定表示。

---

## 2. 画面別 詳細要件・機能仕様

【主要画面遷移フロー】
[アンケート一覧画面] (メイン画面)
   ├── [ + 新規アンケート作成 ] ───> [アンケート作成・編集画面]
   ├── [確認・編集] ────────────> [アンケート詳細・編集画面]
   │                                   ├── [プレビュー]（回答者視点）
   │                                   └── [停止 / 再開]（公開ステータス変更）
   ├── [集計] ─────────────────> [回答集計・データ出力画面]
   │                                   └── CSV / Excel / PDF データ出力
   ├── [送信] ─────────────────> [顧客宛先選択・メール送信画面]
   └── [複製] ─────────────────> 一覧に「下書き」ステータスで即時追加（画面遷移なし）


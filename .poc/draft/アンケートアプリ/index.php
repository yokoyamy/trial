特に、

「管理者画面」
と
「回答者画面」

を明確に分離し、回答者画面から管理者画面へ戻る導線を
一切設けないことを最終仕様とする。


また、アンケート作成・編集画面では、

[キャンセル]    [保存して一覧へ]    状態：[現在の状態 ▼]

を基本情報入力欄より上に配置し、

・保存して一覧へ
  ＝入力内容を保存して一覧画面へ戻る操作

・状態プルダウン
  ＝アンケートの公開状態を変更する操作

・キャンセル
  ＝編集内容を破棄して前の画面へ戻る操作

として明確に役割を分離する。


「下書き保存」は設けない。

保存操作は「保存して一覧へ」に統一する。

新規アンケートを保存する場合は下書きとして保存する。

既存アンケートを編集する場合は、現在の状態を維持して保存する。


状態プルダウンは単一選択のプルダウンとし、
状態変更時には確認ダイアログを表示する。


また、回答形式については、

・単一選択
・複数選択
・自由記述

の3種類を基本とし、

「1行テキスト」
「複数行テキスト」

を別々の回答形式として扱わない。


自由記述は1種類の回答形式として定義し、
実装時に「1行」「複数行」を別の選択肢として
追加してはならない。


本要件を基準として、index.phpの1ファイルによる

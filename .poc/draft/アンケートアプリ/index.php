### ① 要件定義書1：アンケート一覧画面

#### 1. 表示項目・テーブル仕様
* **作成日 / 更新日:** 2行形式で表示（例: `2026/07/25` / `更新: 2026/08/10`）。
* **タイトル:** 太字表示。
* **アンケート期間:** 開始日時 ～ 終了日時（未設定時は「未設定」と表示）。
* **ステータス:** 「公開中」「下書き」「終了」のバッジを色分け表示。
* **回答数:** 現時点での総回答件数を表示（例: `128 件`）。

#### 2. 検索・絞り込み・ソート
* **キーワード検索:** タイトル部分一致検索（テキスト入力＋Enterキー対応）。
* **ステータス絞り込み:** 「すべて / 公開中 / 下書き / 終了」から選択。
* **ソート機能:** 
  * 更新日（新しい順 / 古い順） ※デフォルト：新しい順
  * 回答数（多い順 / 少ない順）
  * アンケート期間開始日（新しい順 / 古い順）

#### 3. ステータス別の操作ボタン制御・挙動
* **公開中:** 
  * 表示ボタン: `[確認・編集]` `[集計]` `[送信]` `[停止]` `[複製]`
  * `[停止]` ボタンは確認ダイアログ表示後、**詳細画面へ遷移せず一覧画面から即時ステータス変更が可能**。
* **下書き:** 
  * 表示ボタン: `[確認・編集]` `[削除]` `[複製]`
  * `[削除]` は確認ダイアログを経て論理削除を実行。
* **終了:** 
  * 表示ボタン: `[確認・編集]`（閲覧モード） `[集計]` `[複製]`
* **複製機能の共通挙動:** どのステータスから複製しても、**一覧画面に「下書き」ステータスとして新規追加され、画面遷移は行わない**。

---

### ② 要件定義書2：アンケート作成・編集画面

#### 1. ヘッダー・アクション
* **タイトル入力:** インライン編集可能なテキストフィールド。
* **「プレビュー」ボタン:** 回答者視点の表示をモーダル（または別タブ）で起動。
* **「保存して一覧へ戻る」ボタン:** DB保存完了後、通知を表示して一覧画面へリダイレクト。
* **「キャンセル」ボタン:** 変更破棄の確認モーダルを表示後、保存せずに一覧へ遷移。

#### 2. 構造設計と編集機能
* **グループ管理:** 
  * アンケート内を複数の「グループ」に分割可能。グループ名の自由編集に対応。
  * ドラッグ＆ドロップ用ハンドル（`⠿`）により、グループ全体の並び替えが可能。
  * グループ削除時は、内包される全質問も一括削除。
* **質問項目（ドラッグ＆ドロップ・自動採番）:**
  * ハンドル操作により同一グループ内の並び替え、および**グループを跨ぐ質問移動が可能**。
  * 質問の追加・削除・移動時に、質問番号（Q1, Q2... またはグループ別 Q1-1, Q1-2...）を**自動で再割り当て**。
　* 質問番号の形式は切り替えできる
* **回答形式:**
  * **単一選択（ラジオボタン）:** 選択肢の追加、選択内容に応じた質問分岐設定に対応。
  * **複数選択（チェックボックス）:** 選択肢の追加に対応。
  * **自由記述（テキストエリア）:** 複数行テキスト入力。
* **その他設定:** 各質問の「必須回答」トグル設定、個別削除機能。

#### 3. プレビュー仕様
* **リアルタイム反映:** DB未保存の入力データ（順序・選択肢等）も即座に描画。
* **表示切替:** 「PC表示」「スマートフォン表示」の切り替えボタンを設置。
* **誤動作防止:** プレビュー内の送信ボタン押下時は実送信を行わず、プレビュー用アラートを表示。


2. システム構成・画面区分
============================================================

2.1 管理者向け画面

以下を管理者向け画面とする。

・アンケート一覧
・アンケート作成・編集
・回答集計・分析
・顧客選択・メール送信
・送信履歴
・kintone連携設定
・メールサーバ設定


2.2 回答者向け画面

以下を回答者向け画面とする。

・アンケート回答画面
・回答確認画面
・回答完了画面


2.3 管理者画面と回答者画面の分離

管理者向け画面と回答者向け画面は役割を完全に分離する。

回答者向け画面には以下を設けない。

・管理者向けヘッダー
・アンケート一覧へのリンク
・管理者画面へのリンク
・管理者画面へ戻るボタン
・kintone設定へのリンク
・メールサーバ設定へのリンク
・集計画面へのリンク
・顧客送信画面へのリンク

回答者は、アンケートURLから回答フローのみを利用する。


============================================================
3. 管理者画面共通ヘッダー
============================================================

管理者向け画面では画面上部に固定ナビゲーションを配置する。

・アンケート一覧
・kintone連携設定
・メールサーバ設定
・ログアウト

回答者向け画面では、この管理者向けヘッダーを表示しない。



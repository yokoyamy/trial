### ④ 要件定義書4：アンケート集計・分析画面

#### 1. ヘッダー・全体集計サマリー（5項目カード）
* 画面上部に固定アンケート名称を表示（誤操作防止のため画面内でのアンケート切替は不可）。
* **サマリー項目:**
  1. **送信対象者数:** 顧客リストからメール送信した総宛先数（例: `200 人`）
  2. **回答数:** 収集された総有効回答数（例: `128 件`）
  3. **未登録顧客からの回答数:** 顧客リスト外（Web公開URL等）からの回答数（例: `8 件`）
  4. **未回答数:** 送信対象者のうち未回答の人数（例: `80 人`）
  5. **回答率:** `（送信対象者からの回答数 ÷ 送信対象者数）× 100`（例: `60.0 %`）

#### 2. 設問別集計結果の表示
* **設問絞り込みパネル:** 設問一覧チェックボックス（一括選択/全解除ボタン付き）で、画面下のグラフ表示/非表示を動的に切り替え。回答形式バッジを表示。
* **選択式設問（単一・複数）:** 回答割合（%）と件数を**横棒グラフ**で表示。「その他」選択肢がある場合、自由記述件数バッジを表示し、クリックで入力テキストと回答者情報をインライン展開。
* **自由記述設問:** 投稿テキストを回答タイムライン形式で表示（会社名・氏名を併記、スクロール対応）。

#### 3. 個別回答一覧テーブル
* 会社名・氏名でのキーワード検索（リアルタイム絞り込み）。
* 回答者ごとの回答日時、「その他」テキストの強調表示。
* `[全回答を表示]` ボタン押下により、該当回答者の全設問に対する回答をモーダルダイアログで閲覧可能。

#### 4. データ出力仕様
* **CSV出力:**
  * **UTF-8（BOM付き）** で出力（Excelでの文字化け防止）。
  * 列構成: `回答ID` `回答日時` `顧客ID` `会社名` `氏名` `設問1...`（設問表示順）。
* **PDF出力:** 画面上で選択・表示中の「集計対象設問」のサマリー・グラフのみを印刷用レイアウトで出力。


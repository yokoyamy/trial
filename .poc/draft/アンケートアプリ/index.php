5. アンケート状態
============================================================

5.1 一覧で表示する状態

・公開中
・下書き
・停止
・終了


5.2 作成・編集画面で扱う状態

状態変更操作は以下とする。

・下書き
・公開
・停止
・再開

「終了」は期間終了等によりシステム上で表示される状態とし、
通常の状態変更操作の対象には含めない。


5.3 状態変更場所

状態変更はアンケート一覧画面では行わない。

状態変更はアンケート作成・編集画面上部に配置する
状態プルダウンから行う。


5.4 状態変更の単一選択

状態は必ず単一選択とする。

UIはプルダウン形式とする。

ラジオボタンやチェックボックスによる複数選択UIは使用しない。

現在の状態に応じて、実行可能な状態のみ選択可能とする。

基本的な状態遷移は以下とする。

下書き
↓
公開

公開中
↓
停止

停止
↓
再開
↓
公開中

終了
↓
変更不可


============================================================
6. アンケート一覧画面
============================================================

6.1 役割

登録されているアンケートを一覧で確認し、各アンケートの
管理操作画面へ移動するための起点とする。

一覧画面では状態変更を直接行わない。


6.2 表示項目

・作成日 / 更新日
・タイトル
・アンケート期間
・ステータス
・回答数
・操作


6.3 ステータス

・公開中
・下書き
・停止
・終了


6.4 検索

タイトルによる部分一致検索を行える。

Enterキーで検索を実行できる。


6.5 フィルター

ステータス：

・すべて
・公開中
・下書き
・停止
・終了


6.6 ソート

更新日：

・新しい順
・古い順

回答数：

・多い順
・少ない順

アンケート期間開始日：

・新しい順
・古い順

初期値は「更新日：新しい順」とする。


6.7 一覧画面の操作

・確認・編集
・集計
・送信
・複製
・削除


6.8 一覧画面に配置しない操作

以下の状態変更操作は一覧画面には配置しない。

・公開
・停止
・再開
・下書きへの変更


6.9 複製

複製時には確認ダイアログを表示する。

複製対象：

・タイトル
・説明
・期間
・グループ
・質問
・選択肢
・必須設定
・条件分岐
・質問番号設定

複製しないもの：

・公開状態
・回答データ
・送信履歴

複製したアンケートは「下書き」とする。

複製後は作成・編集画面へ自動遷移せず、
一覧画面に複製されたアンケートを追加する。


6.10 削除

削除時には確認ダイアログを表示する。

確認後、対象アンケートを一覧から削除する。

モックでは状態に応じた削除可否も表現できるものとする。


============================================================
7. アンケート作成・編集画面
============================================================

7.1 画面上部の配置

アンケート作成・編集画面では、基本情報入力欄より上に
操作エリアを配置する。

配置順は以下とする。


------------------------------------------------------------
アンケート作成・編集

[キャンセル]    [保存して一覧へ]    状態：[現在の状態 ▼]

------------------------------------------------------------

基本情報

アンケートタイトル
[                              ]

アンケート説明
[                              ]

開始日時
[                              ]

終了日時
[                              ]

質問番号の採番方式
○ アンケート全体で通番
○ グループ毎に採番

------------------------------------------------------------


7.2 保存して一覧へ

「保存して一覧へ」を保存操作として使用する。

入力内容を保存し、現在の編集内容を一覧へ反映したうえで
アンケート一覧画面へ戻る。

新規作成時に保存したアンケートの初期状態は「下書き」とする。

既存アンケートを編集している場合は、現在の状態を維持して保存する。

状態を変更したい場合は、保存操作とは別に状態プルダウンから
状態変更を行う。

保存完了後はアンケート一覧画面へ遷移する。


7.3 保存と状態変更の違い

「保存して一覧へ」と「状態プルダウン」は目的が異なる。

【保存して一覧へ】

入力内容を保存し、一覧画面へ戻るための操作。

【状態プルダウン】

アンケートの公開状態を変更するための操作。

したがって、両者を同一UIや同一操作として扱わない。

「保存して一覧へ」は状態プルダウンとは独立したボタンとして
配置する。


7.4 状態プルダウン

基本情報入力欄より上に配置する。

例：

状態：[下書き ▼]

単一選択のプルダウンとする。

現在の状態に応じて選択可能な状態を制御する。


7.5 状態変更確認

状態プルダウンから状態を変更した場合、
選択した時点では変更を確定しない。

必ず確認ダイアログを表示する。


【公開】

「このアンケートを公開しますか？」

[キャンセル] [実行]


【停止】

「このアンケートを停止しますか？」

[キャンセル] [実行]


【再開】

「このアンケートを再開しますか？」

[キャンセル] [実行]


キャンセル：

・状態を変更しない
・変更前の状態へ戻す

実行：

・状態を変更
・画面上の状態表示を即時更新


7.6 状態変更後の表示

下書き → 公開

状態：[公開中]


公開中 → 停止

状態：[停止]


停止 → 再開

状態：[公開中]


7.7 終了状態

終了状態の場合、

状態：[終了]

と表示する。

状態変更操作は無効とする。


7.8 キャンセル

「キャンセル」を押下した場合、
編集内容を破棄する確認ダイアログを表示する。

確認後、変更を破棄して前の画面へ戻る。

保存済みデータには影響を与えない。


============================================================
8. 基本情報
============================================================

基本情報として以下を設定する。

・アンケートタイトル
・アンケート説明
・開始日時
・終了日時
・質問番号の採番方式


============================================================
9. 質問番号の採番方式
============================================================

採番方式は以下の2種類とする。

・アンケート全体で通番
・グループ毎に採番


9.1 アンケート全体で通番

アンケート全体の表示順に応じて連番を付与する。

例：

Q1
Q2
Q3
Q4
Q5


9.2 グループ毎に採番

グループ番号とグループ内質問番号を組み合わせる。

例：

グループ1
  Q1-1
  Q1-2
  Q1-3

グループ2
  Q2-1
  Q2-2

グループ3
  Q3-1
  Q3-2


9.3 初期値

初期値は、

「アンケート全体で通番」

とする。


9.4 自動更新

質問番号はユーザーが直接編集しない。

以下の操作時に自動再計算する。

・質問追加
・質問削除
・質問並び替え
・質問のグループ間移動
・グループ追加
・グループ削除
・グループ並び替え
・採番方式変更


9.5 グループ毎採番時のグループ並び替え

グループ番号も自動的に再計算する。

例：

グループ1
グループ2
グループ3

を並び替えて、

グループ3
グループ1
グループ2

となった場合、画面上のグループ番号を再計算し、

グループ1
グループ2
グループ3

として扱う。

それに伴い質問番号も再計算する。


============================================================
10. グループ管理
============================================================

10.1 グループ構成

各グループには以下を配置する。

・グループタイトル
・グループ操作
・質問一覧
・「＋ 質問を追加」


10.2 グループ追加

グループ一覧の末尾に、

「＋ グループを追加」

を配置する。

押下するとグループ一覧の末尾へ新しいグループを追加する。

追加後はその場で編集できる。


10.3 グループ削除

グループごとに削除操作を配置する。

削除時には確認ダイアログを表示する。

質問が存在する場合は、その旨を確認できる表示とする。


10.4 グループ並び替え

ドラッグ＆ドロップで並び替える。

並び替え後は即時反映する。

グループ毎採番の場合は質問番号も即時更新する。


============================================================
11. 質問管理
============================================================

11.1 質問操作

各質問について以下を設定する。

・質問文
・回答形式
・必須 / 任意
・選択肢
・条件分岐


11.2 質問追加

各グループの質問一覧の末尾に、

「＋ 質問を追加」

を配置する。

質問の途中には追加ボタンを配置しない。


11.3 質問削除

質問ごとに削除操作を配置する。

削除時には確認ダイアログを表示する。


11.4 質問並び替え

ドラッグ＆ドロップで同一グループ内の質問を並び替えられる。


11.5 グループ間移動

質問を別グループへドラッグ＆ドロップして移動できる。

移動後、

・所属グループ
・表示順
・質問番号

を即時更新する。


============================================================
12. 回答形式
============================================================

12.1 単一選択

・ラジオボタン
・選択肢追加
・選択肢削除
・条件分岐


12.2 複数選択

・チェックボックス
・選択肢追加
・選択肢削除


12.3 自由記述

・自由記述入力欄

自由記述は1種類の回答形式として扱う。

「1行テキスト」と「複数行テキスト」は別々の回答形式として
設けない。

回答者画面では、自由記述用の入力欄を表示する。

モックでは画面幅や質問内容に応じて適切な入力欄サイズで表示するが、
これは表示上の違いであり、回答形式として別の種類にはしない。


============================================================
13. 必須回答
============================================================

各質問について必須 / 任意を設定できる。

必須質問が未回答の場合、次へ進む際にエラー表示する。


============================================================
14. 条件分岐
============================================================

単一選択質問について、選択肢ごとに次に表示する質問を
設定できる。

例：

Q1
「サービスを利用したことがありますか？」

はい → Q2
いいえ → Q5

採番方式が変更された場合、画面上の質問番号および
分岐先表示も自動更新する。

モックではプレビュー上で条件分岐による質問表示の変化を
確認できるものとする。


============================================================
15. プレビュー
============================================================

作成・編集画面からプレビューを表示できる。

プレビューでは以下を反映する。

・入力内容
・質問順序
・質問番号
・選択肢
・必須設定
・条件分岐

PC表示とスマートフォン表示を切り替えられる。

プレビュー送信時には実際の送信を行わない。

表示例：

「これはプレビュー表示のため送信されません」


============================================================
16. 保存・キャンセル
============================================================

16.1 保存して一覧へ

「保存して一覧へ」を唯一の編集内容保存操作とする。

入力内容を保存し、アンケート一覧画面へ戻る。

新規作成時は下書きとして保存する。

既存アンケートの編集時は現在の状態を維持して保存する。


16.2 キャンセル

変更を破棄する確認ダイアログを表示する。

確認後、変更を破棄して前の画面へ戻る。


16.3 保存操作の重複禁止

以下のような複数の保存ボタンは設けない。

・下書き保存
・保存
・保存して一覧へ
・一時保存

保存操作は「保存して一覧へ」に統一する。


============================================================
17. 回答者向けアンケート画面
============================================================

17.1 基本方針

回答者向け画面は、管理者向け画面とは完全に分離する。

回答者向け画面には管理者向けナビゲーションを表示しない。


17.2 表示内容

・アンケートタイトル
・アンケート説明
・アンケート期間
・グループタイトル
・質問番号
・質問文
・回答入力欄
・必須表示
・次へ
・戻る
・回答確認


17.3 回答者画面に表示しないもの

以下は回答者向け画面には表示しない。

・アンケート一覧
・管理者画面へ戻るボタン
・管理者メニュー
・kintone連携設定
・メールサーバ設定
・集計画面
・顧客送信画面
・管理者用ログアウト

また、

・キャンセル
・保存して一覧へ
・状態変更操作

等の管理者向け編集操作も表示しない。


17.4 個別回答URL

顧客ごとに個別URLを発行できる。

個別URLから回答した場合、対象顧客と回答情報を紐付ける。


17.5 公開URL

一般公開URLから回答できる。

既存顧客と一致する場合は顧客情報と紐付ける。

一致しない場合は未登録回答者として管理する。


17.6 回答入力

以下の形式に対応する。

・単一選択
・複数選択
・自由記述


17.7 必須チェック

必須項目が未回答の場合、次へ進めない。

画面上に未回答項目を通知する。


17.8 条件分岐

回答内容に応じて次に表示する質問を変更する。

表示される質問番号は設定された採番方式に従う。


============================================================
18. 回答確認・送信
============================================================

回答送信前に入力内容を確認できる。

表示内容：

・質問番号
・質問文
・回答内容
・修正

「回答を送信する」を押下すると確認ダイアログを表示する。

送信後は回答完了画面へ遷移する。


============================================================
19. 回答完了画面
============================================================

回答完了画面には、

「回答ありがとうございました」

等の完了メッセージを表示する。

回答完了画面にも管理者画面への導線を設けない。

「管理者画面へ戻る」等のボタンは配置しない。


============================================================
20. 回答済み表示
============================================================

個別回答URLへ再度アクセスした場合、
すでに回答済みであることを表示する。

アンケートごとに再回答を許可するかどうかを
設定できるものとする。


============================================================
21. 回答者情報
============================================================

回答者情報として以下を管理できる。

・組織名
・氏名
・メールアドレス
・部署名
・電話番号
・住所

回答者のメールアドレス等を利用して既存顧客との紐付けを行う。


============================================================
22. 顧客選択・メール送信

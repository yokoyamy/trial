### ⑤ 要件定義書5：キントーン連携設定画面

#### 1. 接続・認証設定
* **パンくずリスト:** `ホーム > システム設定 > kintone連携設定`
* **入力項目:** サブドメイン（`{subdomain}.cybozu.com`）、ログイン名、パスワード、顧客管理アプリID。
* **通信仕様:** cybozu.com API通信。開発・特定ネットワーク用の「SSL証明書検証スキップ」設定フラグを保持。

#### 2. 項目一覧動的取得・マッピング機能
* **動的取得:** アプリID入力時および「項目一覧を再取得」ボタン押下時に kintone API（`GET /k/v1/app/form/fields.json`）を実行し、フィールド名（日本語）とフィールドコードを取得。
* **直感的UI:** 管理者がフィールドコードを直接手入力する手間を排し、取得した**日本語フィールド名のドロップダウンから選択**してマッピング。
* **マッピング対象（6項目）:**
  * `会社名 (Company)`: 単一選択
  * `氏名 (Name)`: 単一選択
  * `メールアドレス (Email)`: 単一選択（案内送信および顧客照合のキー）
  * `部署名 (Department)`: 単一選択（新規拡張）
  * `電話番号 (Phone)`: 単一選択（新規拡張）
  * `住所 (Address)`: **複数選択可**（都道府県・市区町村・番地など複数フィールドの結合に対応）

#### 3. データ連携・同期処理方式
* **手動同期:** データの自動同期は行わず、**手動実行のみ**。
* **処理ロジック:**
  * **メール送信時:** マッピング設定に基づき、対象顧客の6項目情報を反映。
  * **回答受信・照合時:** 回答されたメールアドレスをキーに既存顧客と照合。既存顧客は回答データを紐付け保存し、未登録顧客は回答情報からkintoneへ新規顧客レコードを登録可能とする。


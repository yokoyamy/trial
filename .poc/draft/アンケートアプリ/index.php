### ③ 要件定義書3：メール送信・回答フォロー画面

#### 1. 画面構成
* **パンくずリスト:** `ホーム > アンケート一覧 > 顧客選択・送信・送信履歴`
* **メインアクション:** 一括送信実行ボタン。
* **アラート通知:** kintone未登録の回答者が存在する場合に警告表示。
* **メールテンプレート編集:** 
  * 件名（1行）および本文（複数行）の入力。
  * **動的変数差し込み:** `{顧客名}`（対象者の氏名に置換）、`{アンケートURL}`（顧客個別の回答URLに置換）。
* **フィルター:** 顧客名、メールアドレス、ステータスによる絞り込み。

#### 2. 顧客一覧テーブル・送信追跡
* **表示項目:**
  * `選択`: チェックボックス（全選択/個別選択。※Web直接回答者は選択不可）。
  * `会社名 / 氏名等`: 会社名（太字）、氏名、メールアドレス、電話番号、住所。
  * `送信ステータス / 履歴追跡`: 最終送信日時、送信回数、`[送信文を確認]` リンク。
  * `回答ステータス`: 「送信済み（未回答）」「回答済み」等の色分けバッジ。
  * `キントーン対応`: `[キントーン登録完了]` ボタン（未対応時） / `✓ キントーン登録完了`（完了後）。
* **重複送信防止・リマインド機能:**
  * 送信完了後、「最終送信日時」の更新と「送信回数」のインクリメントを実行。
  * 送信済みの顧客を再選択して送信しようとした場合、「既に送信済みの宛先が含まれています。再送しますか？」の警告ダイアログを表示。
  * 再送時は「再送専用テンプレート」を自動選択可能。
  * 未回答顧客のみを抽出して一括リマインド送信が可能。

#### 3. 送信履歴追跡・未登録顧客管理
* **一括送信ログ一覧:** 送信日時、種別（初回/リマインド）、送信件数、件名、実行者を記録。
* **送信文確認:** 過去に送信したメール（変数置換済みの実送信文面）をモーダルで閲覧可能。
* **kintone未登録顧客フォロー:** Web公開URL経由の回答者でkintone未登録の場合に「未登録」バッジを表示。kintone側へ登録完了後、ボタン押下で「登録完了」状態へ更新。


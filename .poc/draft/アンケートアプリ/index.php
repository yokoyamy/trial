============================================================

本要件定義を基準としてindex.phpを作成する。

index.phpは、

・HTML
・CSS
・JavaScript

を1ファイルにまとめた動作確認用モックとする。

Apache 2.4 + PHP 8.5 の環境で動作確認できるものとする。

本番用のDB、API、認証、メール送信等は実装しない。

目的は、実際の画面操作を行いながら、

・画面構成
・画面遷移
・状態変更
・入力内容
・質問構成
・グループ構成
・質問番号
・条件分岐

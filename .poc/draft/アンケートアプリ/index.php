## 1. グローバル名前空間の統一とスコープ設計（Scope & Namespace Rule）

### 1.1 `window.App` 単一名前空間の完全義務付け
* すべての状態変数（State）、描画関数（Render）、イベントハンドラー（Action）、API通信関数（API）は、`window.App` オブジェクト直下に階層化して定義すること。
* グローバル空間への生関数（`function hoge()`）の直書き、および即時関数（IIFE）スコープ内へのイベント関数の閉じ込めを禁止する。

### 1.2 動的HTML（テンプレートリテラル）内のイベントバインド規約
* テンプレートリテラルで動的生成するHTML要素のインラインイベント属性は、必ず `App.[カテゴリ].[関数名](引数)` の完全修飾形式で記述する。
